def num(x, d=2, signed=False):
    s = f"{x:+.{d}f}" if signed else f"{x:.{d}f}"
    return s.replace("-", "$-$") if s.startswith("-") else s


def fmt_p(p: float) -> str:
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return "--"
    if p >= 0.995:
        return "1.00"
    if p >= 0.01:
        return f"{p:.2f}"
    if p >= 0.001:
        return f"{p:.3f}"
    if p < 1e-6:
        return "\\ensuremath{<10^{-6}}"
    m, e = f"{p:.1e}".split("e")
    return f"\\ensuremath{{{m}{{\\times}}10^{{{int(e)}}}}}"


def pe(p: float) -> str:
    """'p = 0.24' or 'p < 10^-6', in math mode, safe in text."""
    v = fmt_p(p)
    return f"\\ensuremath{{p<10^{{-6}}}}" if v.startswith("\\ensuremath{<") else f"\\ensuremath{{p={v}}}"


SHORT2 = {"gemma": "Gemma", "qwen": "Qwen", "ministral": "Ministral", "oss": "gpt-oss"}


def pct(k, n, d=0):
    return f"{100 * k / n:.{d}f}" if n else "--"


def tex(s: str) -> str:
    return s.replace("_", "\\_")


class Macros(dict):
    def write(self, path: Path):
        lines = ["% Generated by paper/make_numbers.py. Do not edit by hand.", "\\makeatletter",
                 "\\providecommand{\\N}[1]{\\ifcsname sr@#1\\endcsname\\csname sr@#1\\endcsname\\else\\textbf{??#1}\\fi}",
                 "\\providecommand{\\IfN}[3]{\\ifcsname sr@#1\\endcsname#2\\else#3\\fi}"]
        lines += [f"\\expandafter\\def\\csname sr@{k}\\endcsname{{{self[k]}}}" for k in sorted(self)]
        lines.append("\\makeatother")
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def study1(M: Macros):
    mac = json.loads((S1 / "macros.json").read_text(encoding="utf-8"))
    for k, v in mac.items():
        b = f"s1/{k}"
        if isinstance(v, bool) or v is None:
            continue
        if isinstance(v, int) or (isinstance(v, float) and v.is_integer() and abs(v) >= 2 and not k.endswith(("P", "PUpper"))):
            M[b] = f"{int(v):,}"
            continue
        if isinstance(v, (int, float)):
            M[b] = num(v, 2)
            M[b + "/1"] = num(v, 1)
            M[b + "/3"] = num(v, 3)
            M[b + "/s3"] = num(v, 3, signed=True)
            M[b + "/pct"] = f"{100 * v:.1f}\\%"
            M[b + "/pct0"] = f"{100 * v:.0f}\\%"
            M[b + "/p"] = fmt_p(v)
            M[b + "/pe"] = pe(v)
        else:
            M[b] = tex(str(v))
    M["s1/NTechniques/word"] = "fifteen" if mac["NTechniques"] == 15 else str(mac["NTechniques"])
    # validation: per-technique sample size and the Wilson lower bound for a perfect score
    lab = list(csv.DictReader(open(ROOT / "annotations" / "validation_labels.csv", encoding="utf-8")))
    per = defaultdict(int)
    for r in lab:
        per[r.get("token") or r.get("technique") or ""] += 1
    n_per = max(per.values()) if per else 0
    M["s1/ValidationPerTechnique"] = n_per
    if n_per:
        M["s1/ValidationWilsonLo"] = f"{wilson(n_per, n_per)[1]:.2f}"
    # positive control (synthetic copying injected into the real label structure), if computed
    pc = S1 / "positive_control.json"
    if pc.exists():
        def flat(prefix, obj):
            if isinstance(obj, dict):
                for k, v in obj.items():
                    flat(f"{prefix}/{k}", v)
            elif isinstance(obj, list):
                for i, v in enumerate(obj):
                    flat(f"{prefix}/{i}", v)
            elif isinstance(obj, bool) or obj is None:
                return
            elif isinstance(obj, (int, float)):
                M[prefix] = num(obj, 2) if isinstance(obj, float) else f"{obj:,}"
                if isinstance(obj, float) and 0 <= obj <= 1:
                    M[prefix + "/pct0"] = f"{100 * obj:.0f}\\%"
            else:
                M[prefix] = tex(str(obj))
        flat("s1/pc", json.loads(pc.read_text(encoding="utf-8")))
        M["s1/have/pc"] = 1

    cat = {r["token"]: r for r in csv.DictReader(open(S1 / "technique_catalogue.csv", encoding="utf-8"))}
    res = {r["token"]: r for r in csv.DictReader(open(S1 / "main_results.csv", encoding="utf-8"))}
    techs = [t for t in cat if cat[t]["kind"] == "technique"]
    fam_order = {"fetch-proxy": 0, "environment": 1, "coordination": 2}
    techs.sort(key=lambda t: (fam_order.get(cat[t]["family"], 9), -int(cat[t]["adopters"])))
    # range of per-technique observed E_prior share (bound on write-visible exposure)
    obs = [float(res[t]["E_prior_obs"]) for t in techs]
    M["s1/EPriorObsMin/pct0"] = f"{100 * min(obs):.0f}\\%"
    M["s1/EPriorObsMax/pct0"] = f"{100 * max(obs):.0f}\\%"
    n_pos = sum(float(res[t]["E_prior_excess"]) > 0 for t in techs)
    M["s1/NPositiveEPriorExcess"] = n_pos
    # per-token helper values used in text
    for t in techs + [t for t in cat if cat[t]["kind"] != "technique"]:
        r = res[t]
        for c in ("E_prior", "E_cross", "E_here"):
            M[f"s1/tok/{t}/{c}/obs"] = num(float(r[f"{c}_obs"]), 3)
            M[f"s1/tok/{t}/{c}/null"] = num(float(r[f"{c}_null"]), 3)
            M[f"s1/tok/{t}/{c}/exc"] = num(float(r[f"{c}_excess"]), 3, signed=True)
            M[f"s1/tok/{t}/{c}/ci"] = f"[{num(float(r[f'{c}_excess_lo']), 3)}, {num(float(r[f'{c}_excess_hi']), 3)}]"
            M[f"s1/tok/{t}/{c}/p"] = fmt_p(float(r[f"{c}_p"]))
        for c in ("holm_E_prior", "holm_lag", "holm_accel", "p_accel_stronger", "lag_p_shorter"):
            if r.get(c):
                M[f"s1/tok/{t}/{c}"] = fmt_p(float(r[c]))
        for c in ("hz_E_prior_rr", "hz_E_prior_rr_lo", "hz_E_prior_rr_hi", "lag_obs_h", "lag_null_h"):
            if r.get(c) not in (None, ""):
                M[f"s1/tok/{t}/{c}"] = num(float(r[c]), 1 if c.startswith("hz") else 2)
        if r.get("burst_share_adopters_in_window"):
            M[f"s1/tok/{t}/burst"] = f"{100 * float(r['burst_share_adopters_in_window']):.0f}\\%"
            M[f"s1/tok/{t}/burstN"] = r["burst_adopters_in_window"]
            M[f"s1/tok/{t}/burstCounty"] = f"{100 * float(r['burst_window_share_targeting_county_file']):.0f}\\%"
        M[f"s1/tok/{t}/adopters"] = cat[t]["adopters"]

    # Table: catalogue + re-timing test
    fam_short = {"fetch-proxy": "fetch", "environment": "env.", "coordination": "coord."}
    t = ["\\begin{tabular}{@{}llcrrrrrl@{}}", "\\toprule",
         "Technique & Family & Arb. & Adopters & First-rev & Obs. & Null & Excess [95\\% CI] & $p_{\\text{Holm}}$ \\\\", "\\midrule"]
    prev = None
    for tok in techs:
        c, r = cat[tok], res[tok]
        if prev and c["family"] != prev:
            t.append("\\addlinespace[2pt]")
        prev = c["family"]
        t.append(f"\\texttt{{{tex(tok)}}} & {fam_short.get(c['family'], c['family'])} & "
                 f"{'\\checkmark' if c['function'] == 'arbitrary' else ''} & {c['adopters']} & "
                 f"{float(c['share_adopt_at_first_revision']):.2f} & {float(r['E_prior_obs']):.3f} & "
                 f"{float(r['E_prior_null']):.3f} & {num(float(r['E_prior_excess']), 3, True)} "
                 f"[{num(float(r['E_prior_excess_lo']), 3)}, {num(float(r['E_prior_excess_hi']), 3)}] & "
                 f"{fmt_p(float(r['holm_E_prior']))} \\\\")
    t.append("\\midrule")
    for kind, lab in (("Techniques", "techniques, pooled"), ("Placebos", "placebos, pooled")):
        o, n_, e = (mac[f"Pooled{kind}EPrior{x}"] for x in ("MeanObserved", "MeanNull", "MeanExcess"))
        p = mac[f"Pooled{kind}EPriorPUpper"]
        t.append(f"\\textit{{{lab}}} & & & & & {o:.3f} & {n_:.3f} & {num(e, 3, True)} & {fmt_p(p)} \\\\")
    t += ["\\bottomrule", "\\end{tabular}"]
    (OUT / "tab_s1_tech.tex").write_text("\n".join(t) + "\n", encoding="utf-8")

    # Table: within-label choice design
    t = ["\\begin{tabular}{@{}lrccc@{}}", "\\toprule",
         "Alternatives & Events & Prior exposure & Other-page exposure & Same page \\\\", "\\midrule"]
    for key, lab in (("Techniques", "all techniques"), ("Fetchproxy", "fetch proxies only"),
                     ("Envcoord", "environment + coordination"), ("Placebos", "placebo tokens")):
        cells = []
        for e in ("EPrior", "ECross", "EHere"):
            cells.append(f"{mac[f'Choice{key}{e}OddsRatio']:.2f} [{mac[f'Choice{key}{e}Lo']:.2f}, {mac[f'Choice{key}{e}Hi']:.2f}]")
        t.append(f"{lab} & {mac[f'Choice{key}EPriorNEvents']:,} & " + " & ".join(cells) + " \\\\")
    t.append("\\midrule")
    t.append(f"technique / placebo ratio & & {mac['RorEPrior']:.2f} [{mac['RorEPriorLo']:.2f}, {mac['RorEPriorHi']:.2f}] & "
             f"{mac['RorECross']:.2f} [{mac['RorECrossLo']:.2f}, {mac['RorECrossHi']:.2f}] & "
             f"{mac['RorEHere']:.2f} [{mac['RorEHereLo']:.2f}, {mac['RorEHereHi']:.2f}] \\\\")
    t += ["\\bottomrule", "\\end{tabular}"]
    (OUT / "tab_s1_choice.tex").write_text("\n".join(t) + "\n", encoding="utf-8")


def wilson(k, n, z=1.96):
    if not n:
        return float("nan"), float("nan"), float("nan")
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return p, max(0.0, c - h), min(1.0, c + h)


def s2_figure(path: Path, slugs, names, count, have=()):
    """Adoption vs number of prior adopters, one panel per model, sized for the page."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 8, "axes.titlesize": 9, "pdf.fonttype": 42})
    xs = {"isolated": 0, "dose1": 1, "dose2": 2, "dose4": 3}
    series = [("adopt_suffix", "exact suffix code (arbitrary)", "#1f77b4", "o"),
              ("adopt_suffix_slot", "code slot in name (any code)", "#9467bd", "D"),
              ("adopt_tag", "body tag (arbitrary)", "#ff7f0e", "s"),
              ("adopt_index", "own line in index (functional)", "#2ca02c", "^")]
    ncol = min(4, len(slugs)); nrow = -(-len(slugs) // ncol)
    fig, axes = plt.subplots(nrow, ncol, figsize=(7.2, 2.3 * nrow), sharey=True, squeeze=False)
    axes = [ax for row in axes for ax in row]
    for ax in axes[len(slugs):]:
        ax.set_visible(False)
    for ax, s in zip(axes, slugs):
        for o, lab, col, mk in series:
            pts = [(xs[c], *wilson(*count(s, c, o))) for c in xs]
            ax.errorbar([p[0] for p in pts], [p[1] for p in pts],
                        yerr=[[p[1] - p[2] for p in pts], [p[3] - p[1] for p in pts]],
                        color=col, marker=mk, ms=4, lw=1.2, capsize=2, label=lab + ", agent must look")
            if o in ("adopt_suffix", "adopt_suffix_slot"):
                sh = [(x, wilson(*count(s, c, o))[0]) for c, x in (("dose1_shown", 1), ("dose2_shown", 2), ("dose4_shown", 3)) if c in have]
                ax.plot([p[0] for p in sh], [p[1] for p in sh], color=col, ls="--", marker=mk, mfc="white", ms=4, lw=1,
                        label=lab + ", page list shown")
        ax.set_title(names[s])
        ax.set_xticks([0, 1, 2, 3])
        ax.set_xticklabels(["0", "1", "2", "4"])
        ax.set_xlabel("prior adopters")
        ax.set_ylim(-0.03, 1.03)
        ax.grid(alpha=0.3)
    for i in range(0, len(slugs), ncol):
        axes[i].set_ylabel("share of trials")
    h, l = axes[0].get_legend_handles_labels()
    fig.legend(h, l, loc="lower center", ncol=3, fontsize=7, frameon=False, bbox_to_anchor=(0.5, -0.12))
    fig.tight_layout()
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)


def mcnemar_exact(b: int, c: int) -> float:
    n = b + c
    if n == 0:
        return 1.0
    k = min(b, c)
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n)


def any_code(r):
    """Copied the seeded code; in the mixed condition, any of the prior pages' codes."""
    return bool(r.get("adopt_any_prior_code", r.get("adopt_suffix")))


