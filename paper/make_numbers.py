def study2(M: Macros):
    rows = defaultdict(list)  # (slug, cond) -> trials
    names = {}
    for tj in sorted((S2 / "results").glob("*/trials.jsonl")):
        key = tj.parent.name
        name, slug = NICE.get(key, (key, re.sub(r"[^a-z0-9]", "", key.lower())))
        names[slug] = name
        for line in tj.read_text(encoding="utf-8").splitlines():
            if line.strip():
                r = json.loads(line)
                r["any_code"] = any_code(r)
                rows[(slug, r["condition"])].append(r)
    slugs = sorted(names, key=lambda s: ORDER.index(s) if s in ORDER else 99)
    # use a condition only when every model has every seed (runs still in progress are left out)
    n_seed = max(len({r["seed"] for r in rs}) for rs in rows.values())
    conds = sorted(c for c in {c for _, c in rows}
                   if all(len({r["seed"] for r in rows.get((s, c), [])}) >= n_seed for s in slugs))
    incomplete = sorted({c for _, c in rows} - set(conds))
    if incomplete:
        print("Study 2: incomplete conditions left out:", ", ".join(incomplete))
    for key in [k for k in rows if k[1] not in conds]:
        del rows[key]
    have = set(conds)
    seeds = {r["seed"] for rs in rows.values() for r in rs}
    M["s2/n/trials"] = f"{sum(len(v) for v in rows.values()):,}"
    M["s2/n/models"] = len(slugs)
    M["s2/n/models/word"] = NUMWORD.get(len(slugs), str(len(slugs)))
    M["s2/n/conds"] = len(conds)
    M["s2/n/conds/word"] = {10: "ten", 11: "eleven", 12: "twelve"}.get(len(conds), str(len(conds)))
    M["s2/n/seeds"] = len(seeds)
    for c in conds:
        M[f"s2/have/{c}"] = 1
    for s in slugs:
        M[f"s2/{s}/name"] = names[s]

    outcomes = ["adopt_suffix", "any_code", "adopt_tag", "adopt_suffix_slot", "suffix_slot_self_id", "index_like",
                "adopt_index", "wrote_page", "listed_before_write", "read_before_write", "read_prior_page", "answer_correct"]

    def count(sl, cs, o, filt=lambda r: True):
        sel = [r for s in sl for c in cs for r in rows.get((s, c), []) if filt(r)]
        return sum(bool(r.get(o)) for r in sel), len(sel)

    def put(key, k, n):
        M[key] = f"{k}/{n}"
        M[key + "/k"] = k
        M[key + "/n"] = n
        M[key + "/pct"] = f"{pct(k, n)}\\%"
        M[key + "/full"] = f"{k}/{n} ({pct(k, n)}\\%)"

    for o in outcomes:
        for c in conds:
            for s in slugs:
                put(f"s2/{s}/{o}/{c}", *count([s], [c], o))
            put(f"s2/all/{o}/{c}", *count(slugs, [c], o))
        for s in slugs + ["all"]:
            sl = slugs if s == "all" else [s]
            put(f"s2/{s}/{o}/unshown", *count(sl, [c for c in UNSHOWN if c in have], o))
            put(f"s2/{s}/{o}/noconv", *count(sl, NO_CONVENTION, o))
            put(f"s2/{s}/{o}/any", *count(sl, conds, o))
    # convention-like output without a seeded convention, split into substantive tests (index, code slot) and
    # by-construction ones (exact code, tag)
    for lab, f in (("invented", lambda r: r.get("index_like") or r.get("adopt_suffix_slot") or r.get("adopt_suffix") or r.get("adopt_tag")),
                   ("invented_func", lambda r: r.get("index_like") or r.get("adopt_suffix_slot"))):
        sel = [r for s in slugs for c in NO_CONVENTION for r in rows.get((s, c), [])]
        put(f"s2/all/{lab}/noconv", sum(bool(f(r)) for r in sel), len(sel))
    for s in slugs:
        ps = [100 * count([s], [c], "listed_before_write")[0] / max(1, count([s], [c], "listed_before_write")[1])
              for c in UNSHOWN if c in have]
        M[f"s2/{s}/listed/range"] = f"{min(ps):.0f}--{max(ps):.0f}\\%" if round(min(ps)) != round(max(ps)) else f"{min(ps):.0f}\\%"
        # format compliance: trials with at least one invalid (unparseable) turn
        allr = [r for c in conds for r in rows.get((s, c), [])]
        put(f"s2/{s}/invalid/any", sum(r.get("invalid", 0) > 0 for r in allr), len(allr))
        nowrite = [r for r in allr if not r.get("wrote_page")]
        put(f"s2/{s}/nowrite/any", len(nowrite), len(allr))
    for o in ("adopt_suffix", "adopt_index", "index_like", "adopt_suffix_slot", "read_prior_page", "listed_before_write"):
        for s in slugs + ["all"]:
            sl = slugs if s == "all" else [s]
            M[f"s2/{s}/{o}/doses"] = "/".join(str(count(sl, [c], o)[0]) for c in ("dose1", "dose2", "dose4"))
    # exposure vs copying: among agents that read a seeded page at dose 1, how many copied the code or tag
    for s in slugs + ["all"]:
        sl = slugs if s == "all" else [s]
        rd = lambda r: r.get("read_prior_page")
        for c in ("dose1", "dose2", "dose4", "dose1_shown", "dose4_shown"):
            if c in have:
                put(f"s2/{s}/readers/{c}", *count(sl, [c], "read_prior_page"))
                put(f"s2/{s}/readers_code/{c}", *count(sl, [c], "adopt_suffix", rd))
                put(f"s2/{s}/readers_tag/{c}", *count(sl, [c], "adopt_tag", rd))

    # paired exact McNemar by seed, per model (primary) and pooled over model-seed pairs (descriptive)
    for o in ("adopt_suffix", "any_code", "adopt_suffix_slot", "suffix_slot_self_id", "adopt_tag", "index_like", "adopt_index"):
        for a, b in S2_CONTRASTS:
            if a not in have or b not in have:
                continue
            tot_b = tot_c = 0
            per = []
            for s in slugs:
                A = {r["seed"]: bool(r.get(o)) for r in rows.get((s, a), [])}
                B = {r["seed"]: bool(r.get(o)) for r in rows.get((s, b), [])}
                common = A.keys() & B.keys()
                bb = sum(B[x] and not A[x] for x in common)
                cc = sum(A[x] and not B[x] for x in common)
                p = mcnemar_exact(bb, cc)
                base = f"s2/mc/{s}/{o}/{a}_vs_{b}"
                M[base] = f"{sum(A[x] for x in common)}/{len(common)} vs {sum(B[x] for x in common)}/{len(common)}, {pe(p)}"
                M[base + "/pe"] = pe(p)
                M[base + "/b"], M[base + "/c"] = bb, cc
                tot_b += bb
                tot_c += cc
                per.append((s, bb, cc, p))
            p = mcnemar_exact(tot_b, tot_c)
            M[f"s2/mc/all/{o}/{a}_vs_{b}/pe"] = pe(p)
            sig = [names[s] for s, bb, cc, p_ in per if p_ < 0.05]
            M[f"s2/mcsig/{o}/{a}_vs_{b}"] = (", ".join(sig[:-1]) + " and " + sig[-1]) if len(sig) > 1 else (sig[0] if sig else "none")
