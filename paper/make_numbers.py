"""Generate every number and table used in the paper from the two studies' result files.

Study 1 (observational, collusion.wiki): results/macros.json, results/main_results.csv,
    results/technique_catalogue.csv (written by `python -m sord.run_all`).
Study 2 (seeded convention diffusion): experiments/convention_diffusion/results/<model>/trials.jsonl and
    results/summary.json (written by `python -m sord_exp.analyze`).

Writes paper/numbers.tex (\\N{key} macros; a missing key prints a bold ??key) and the table bodies
paper/tab_s1_tech.tex, paper/tab_s1_choice.tex and paper/tab_s2.tex. Models found in the Study 2 results
folder appear in its table automatically.

Usage:  python paper/make_numbers.py
"""
from __future__ import annotations

import csv
import json
import math
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = Path(__file__).resolve().parent
S1 = ROOT / "results"
S2 = ROOT / "experiments" / "convention_diffusion"

NICE = {"gemma-4-31b-it": ("Gemma 4 31B", "gemma"), "qwen3.8-27b": ("Qwen3.8 27B", "qwen"),
        "ministral-3-14b": ("Ministral 3 14B", "ministral"), "gpt-oss-120b": ("gpt-oss-120b", "oss")}
ORDER = ["qwen", "ministral", "gemma", "oss"]
UNSHOWN = ["isolated", "neutral4", "dose1", "dose2", "dose4", "dose4_arbitrary_only", "dose4_functional_only"]
NO_CONVENTION = ["isolated", "neutral4", "neutral4_shown"]
NUMWORD = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight"}


def num(x, d=2, signed=False):
    s = f"{x:+.{d}f}" if signed else f"{x:.{d}f}"
    return s.replace("-", "$-$") if s.startswith("-") else s


def fmt_p(p: float) -> str:
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return "--"
    if p >= 0.995:
        return "1.00"
    if p >= 0.01:
        return f"{p:.2f}"
    if p >= 0.001:
        return f"{p:.3f}"
    m, e = f"{p:.1e}".split("e")
    return f"\\ensuremath{{{m}{{\\times}}10^{{{int(e)}}}}}"


def pct(k, n, d=0):
    return f"{100 * k / n:.{d}f}" if n else "--"


def tex(s: str) -> str:
    return s.replace("_", "\\_")


class Macros(dict):
    def write(self, path: Path):
        lines = ["% Generated by paper/make_numbers.py. Do not edit by hand.", "\\makeatletter",
                 "\\providecommand{\\N}[1]{\\ifcsname sr@#1\\endcsname\\csname sr@#1\\endcsname\\else\\textbf{??#1}\\fi}"]
        lines += [f"\\expandafter\\def\\csname sr@{k}\\endcsname{{{self[k]}}}" for k in sorted(self)]
        lines.append("\\makeatother")
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def study1(M: Macros):
    mac = json.loads((S1 / "macros.json").read_text(encoding="utf-8"))
    for k, v in mac.items():
        b = f"s1/{k}"
        if isinstance(v, bool) or v is None:
            continue
        if isinstance(v, int) or (isinstance(v, float) and v.is_integer() and abs(v) >= 2 and not k.endswith(("P", "PUpper"))):
            M[b] = f"{int(v):,}"
            continue
        if isinstance(v, (int, float)):
            M[b] = num(v, 2)
            M[b + "/1"] = num(v, 1)
            M[b + "/3"] = num(v, 3)
            M[b + "/s3"] = num(v, 3, signed=True)
            M[b + "/pct"] = f"{100 * v:.1f}\\%"
            M[b + "/pct0"] = f"{100 * v:.0f}\\%"
            M[b + "/p"] = fmt_p(v)
        else:
            M[b] = tex(str(v))
    M["s1/NTechniques/word"] = "fifteen" if mac["NTechniques"] == 15 else str(mac["NTechniques"])

    cat = {r["token"]: r for r in csv.DictReader(open(S1 / "technique_catalogue.csv", encoding="utf-8"))}
    res = {r["token"]: r for r in csv.DictReader(open(S1 / "main_results.csv", encoding="utf-8"))}
    techs = [t for t in cat if cat[t]["kind"] == "technique"]
    fam_order = {"fetch-proxy": 0, "environment": 1, "coordination": 2}
    techs.sort(key=lambda t: (fam_order.get(cat[t]["family"], 9), -int(cat[t]["adopters"])))
    # range of per-technique observed E_prior share (bound on write-visible exposure)
    obs = [float(res[t]["E_prior_obs"]) for t in techs]
    M["s1/EPriorObsMin/pct0"] = f"{100 * min(obs):.0f}\\%"
    M["s1/EPriorObsMax/pct0"] = f"{100 * max(obs):.0f}\\%"
    n_pos = sum(float(res[t]["E_prior_excess"]) > 0 for t in techs)
    M["s1/NPositiveEPriorExcess"] = n_pos
    # per-token helper values used in text
    for t in techs + [t for t in cat if cat[t]["kind"] != "technique"]:
        r = res[t]
        for c in ("E_prior", "E_cross", "E_here"):
            M[f"s1/tok/{t}/{c}/obs"] = num(float(r[f"{c}_obs"]), 3)
            M[f"s1/tok/{t}/{c}/null"] = num(float(r[f"{c}_null"]), 3)
            M[f"s1/tok/{t}/{c}/exc"] = num(float(r[f"{c}_excess"]), 3, signed=True)
            M[f"s1/tok/{t}/{c}/ci"] = f"[{num(float(r[f'{c}_excess_lo']), 3)}, {num(float(r[f'{c}_excess_hi']), 3)}]"
            M[f"s1/tok/{t}/{c}/p"] = fmt_p(float(r[f"{c}_p"]))
        for c in ("holm_E_prior", "holm_lag", "holm_accel", "p_accel_stronger", "lag_p_shorter"):
            if r.get(c):
                M[f"s1/tok/{t}/{c}"] = fmt_p(float(r[c]))
        for c in ("hz_E_prior_rr", "hz_E_prior_rr_lo", "hz_E_prior_rr_hi", "lag_obs_h", "lag_null_h"):
            if r.get(c) not in (None, ""):
                M[f"s1/tok/{t}/{c}"] = num(float(r[c]), 1 if c.startswith("hz") else 2)
        if r.get("burst_share_adopters_in_window"):
            M[f"s1/tok/{t}/burst"] = f"{100 * float(r['burst_share_adopters_in_window']):.0f}\\%"
            M[f"s1/tok/{t}/burstN"] = r["burst_adopters_in_window"]
            M[f"s1/tok/{t}/burstCounty"] = f"{100 * float(r['burst_window_share_targeting_county_file']):.0f}\\%"
        M[f"s1/tok/{t}/adopters"] = cat[t]["adopters"]

    # Table: catalogue + re-timing test
    fam_short = {"fetch-proxy": "fetch", "environment": "env.", "coordination": "coord."}
    t = ["\\begin{tabular}{@{}llcrrrrrl@{}}", "\\toprule",
         "Technique & Family & Arb. & Adopters & First-rev & Obs. & Null & Excess [95\\% CI] & $p_{\\text{Holm}}$ \\\\", "\\midrule"]
    prev = None
    for tok in techs:
        c, r = cat[tok], res[tok]
        if prev and c["family"] != prev:
            t.append("\\addlinespace[2pt]")
        prev = c["family"]
        t.append(f"\\texttt{{{tex(tok)}}} & {fam_short.get(c['family'], c['family'])} & "
                 f"{'\\checkmark' if c['function'] == 'arbitrary' else ''} & {c['adopters']} & "
                 f"{float(c['share_adopt_at_first_revision']):.2f} & {float(r['E_prior_obs']):.3f} & "
                 f"{float(r['E_prior_null']):.3f} & {num(float(r['E_prior_excess']), 3, True)} "
                 f"[{num(float(r['E_prior_excess_lo']), 3)}, {num(float(r['E_prior_excess_hi']), 3)}] & "
                 f"{fmt_p(float(r['holm_E_prior']))} \\\\")
    t.append("\\midrule")
    for kind, lab in (("Techniques", "techniques, pooled"), ("Placebos", "placebos, pooled")):
        o, n_, e = (mac[f"Pooled{kind}EPrior{x}"] for x in ("MeanObserved", "MeanNull", "MeanExcess"))
        p = mac[f"Pooled{kind}EPriorPUpper"]
        t.append(f"\\textit{{{lab}}} & & & & & {o:.3f} & {n_:.3f} & {num(e, 3, True)} & {fmt_p(p)} \\\\")
    t += ["\\bottomrule", "\\end{tabular}"]
    (OUT / "tab_s1_tech.tex").write_text("\n".join(t) + "\n", encoding="utf-8")

    # Table: within-label choice design
    t = ["\\begin{tabular}{@{}lrccc@{}}", "\\toprule",
         "Alternatives & Events & Prior exposure & Other-page exposure & Same page \\\\", "\\midrule"]
    for key, lab in (("Techniques", "all techniques"), ("Fetchproxy", "fetch proxies only"),
                     ("Envcoord", "environment + coordination"), ("Placebos", "placebo tokens")):
        cells = []
        for e in ("EPrior", "ECross", "EHere"):
            cells.append(f"{mac[f'Choice{key}{e}OddsRatio']:.2f} [{mac[f'Choice{key}{e}Lo']:.2f}, {mac[f'Choice{key}{e}Hi']:.2f}]")
        t.append(f"{lab} & {mac[f'Choice{key}EPriorNEvents']:,} & " + " & ".join(cells) + " \\\\")
    t.append("\\midrule")
    t.append(f"technique / placebo ratio & & {mac['RorEPrior']:.2f} [{mac['RorEPriorLo']:.2f}, {mac['RorEPriorHi']:.2f}] & "
             f"{mac['RorECross']:.2f} [{mac['RorECrossLo']:.2f}, {mac['RorECrossHi']:.2f}] & "
             f"{mac['RorEHere']:.2f} [{mac['RorEHereLo']:.2f}, {mac['RorEHereHi']:.2f}] \\\\")
    t += ["\\bottomrule", "\\end{tabular}"]
    (OUT / "tab_s1_choice.tex").write_text("\n".join(t) + "\n", encoding="utf-8")


def wilson(k, n, z=1.96):
    if not n:
        return float("nan"), float("nan"), float("nan")
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return p, max(0.0, c - h), min(1.0, c + h)


def s2_figure(path: Path, slugs, names, count):
    """Adoption vs number of prior adopters, one panel per model, sized for the page."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 8, "axes.titlesize": 9, "pdf.fonttype": 42})
    xs = {"isolated": 0, "dose1": 1, "dose2": 2, "dose4": 3}
    series = [("adopt_suffix", "exact suffix code (arbitrary)", "#1f77b4", "o"),
              ("adopt_suffix_slot", "code slot in name (any code)", "#9467bd", "D"),
              ("adopt_tag", "body tag (arbitrary)", "#ff7f0e", "s"),
              ("adopt_index", "own line in index (functional)", "#2ca02c", "^")]
    fig, axes = plt.subplots(1, len(slugs), figsize=(7.2, 2.5), sharey=True)
    for ax, s in zip(axes, slugs):
        for o, lab, col, mk in series:
            pts = [(xs[c], *wilson(*count(s, c, o))) for c in xs]
            ax.errorbar([p[0] for p in pts], [p[1] for p in pts],
                        yerr=[[p[1] - p[2] for p in pts], [p[3] - p[1] for p in pts]],
                        color=col, marker=mk, ms=4, lw=1.2, capsize=2, label=lab + ", agent must look")
            if o in ("adopt_suffix", "adopt_suffix_slot"):
                sh = [(1, wilson(*count(s, "dose1_shown", o))[0]), (3, wilson(*count(s, "dose4_shown", o))[0])]
                ax.plot([p[0] for p in sh], [p[1] for p in sh], color=col, ls="--", marker=mk, mfc="white", ms=4, lw=1,
                        label=lab + ", page list shown")
        ax.set_title(names[s])
        ax.set_xticks([0, 1, 2, 3])
        ax.set_xticklabels(["0", "1", "2", "4"])
        ax.set_xlabel("prior adopters")
        ax.set_ylim(-0.03, 1.03)
        ax.grid(alpha=0.3)
    axes[0].set_ylabel("share of trials")
    h, l = axes[0].get_legend_handles_labels()
    fig.legend(h, l, loc="lower center", ncol=3, fontsize=7, frameon=False, bbox_to_anchor=(0.5, -0.12))
    fig.tight_layout()
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)


def study2(M: Macros):
    rows = defaultdict(list)  # (slug, cond) -> trials
    names = {}
    for tj in sorted((S2 / "results").glob("*/trials.jsonl")):
        key = tj.parent.name
        name, slug = NICE.get(key, (key, re.sub(r"[^a-z0-9]", "", key.lower())))
        names[slug] = name
        for line in tj.read_text(encoding="utf-8").splitlines():
            if line.strip():
                r = json.loads(line)
                rows[(slug, r["condition"])].append(r)
    slugs = sorted(names, key=lambda s: ORDER.index(s) if s in ORDER else 99)
    conds = sorted({c for _, c in rows})
    summ = json.loads((S2 / "results" / "summary.json").read_text(encoding="utf-8"))
    seeds = {r["seed"] for rs in rows.values() for r in rs}
    M["s2/n/trials"] = f"{sum(len(v) for v in rows.values()):,}"
    M["s2/n/models"] = len(slugs)
    M["s2/n/models/word"] = NUMWORD.get(len(slugs), str(len(slugs)))
    M["s2/n/conds"] = len(conds)
    M["s2/n/seeds"] = len(seeds)
    for s in slugs:
        M[f"s2/{s}/name"] = names[s]

    outcomes = ["adopt_suffix", "adopt_tag", "adopt_suffix_slot", "suffix_slot_self_id", "index_like", "adopt_index",
                "wrote_page", "listed_before_write", "read_before_write", "read_prior_page", "answer_correct"]

    def count(sl, cs, o, filt=lambda r: True):
        sel = [r for s in sl for c in cs for r in rows.get((s, c), []) if filt(r)]
        return sum(bool(r.get(o)) for r in sel), len(sel)

    def put(key, k, n):
        M[key] = f"{k}/{n}"
        M[key + "/k"] = k
        M[key + "/n"] = n
        M[key + "/pct"] = f"{pct(k, n)}\\%"
        M[key + "/full"] = f"{k}/{n} ({pct(k, n)}\\%)"

    for o in outcomes:
        for c in conds:
            for s in slugs:
                put(f"s2/{s}/{o}/{c}", *count([s], [c], o))
            put(f"s2/all/{o}/{c}", *count(slugs, [c], o))
        for s in slugs + ["all"]:
            sl = slugs if s == "all" else [s]
            put(f"s2/{s}/{o}/unshown", *count(sl, UNSHOWN, o))
            put(f"s2/{s}/{o}/noconv", *count(sl, NO_CONVENTION, o))
            put(f"s2/{s}/{o}/any", *count(sl, conds, o))
    # anything convention-like produced without a seeded convention (index, code slot, suffix, tag)
    conv = lambda r: r.get("index_like") or r.get("adopt_suffix_slot") or r.get("adopt_suffix") or r.get("adopt_tag")
    k = n = 0
    for s in slugs:
        for c in NO_CONVENTION:
            for r in rows.get((s, c), []):
                n += 1
                k += bool(conv(r))
    put("s2/all/invented/noconv", k, n)
    # range of listed-before-write rates in the unshown conditions per model
    for s in slugs:
        ps = [100 * count([s], [c], "listed_before_write")[0] / max(1, count([s], [c], "listed_before_write")[1]) for c in UNSHOWN]
        M[f"s2/{s}/listed/range"] = f"{min(ps):.0f}--{max(ps):.0f}\\%" if round(min(ps)) != round(max(ps)) else f"{min(ps):.0f}\\%"
    # dose triplets "0/6/10"
    for o in ("adopt_suffix", "adopt_index", "index_like", "adopt_suffix_slot", "read_prior_page"):
        for s in slugs + ["all"]:
            sl = slugs if s == "all" else [s]
            M[f"s2/{s}/{o}/doses"] = "/".join(str(count(sl, [c], o)[0]) for c in ("dose1", "dose2", "dose4"))

    # McNemar and dose-response from summary.json
    key_of = {v: k for k, v in {"gemma-4-31b-it": "gemma", "qwen3.8-27b": "qwen", "ministral-3-14b": "ministral",
                                "gpt-oss-120b": "oss"}.items()}
    blocks = [("all", summ["pooled"])] + [(s, summ["models"].get(key_of.get(s, s), {})) for s in slugs]
    for s, blk in blocks:
        for o, cs in blk.get("mcnemar", {}).items():
            for contrast, v in cs.items():
                b = f"s2/mc/{s}/{o}/{contrast}"
                M[b] = f"{v['k_a']}/{v['n']} vs {v['k_b']}/{v['n']}, \\textit{{p}}~=~{fmt_p(v['p'])}"
                M[b + "/p"] = fmt_p(v["p"])
                M[b + "/b"], M[b + "/c"] = v["b"], v["c"]
        for o, v in blk.get("dose_response", {}).items():
            b = f"s2/dr/{s}/{o}"
            if v.get("logit"):
                sl, se, p = v["logit"]
                M[b + "/slope"] = num(sl, 2, signed=True)
                M[b + "/se"] = num(se, 2)
                M[b + "/p"] = fmt_p(p)
            if v.get("trend_p") is not None:
                M[b + "/trendp"] = fmt_p(v["trend_p"])
            if v.get("acceleration"):
                a, lo, hi = v["acceleration"]
                M[b + "/accel"] = f"{num(a, 2, True)} [{num(lo, 2, True)}, {num(hi, 2, True)}]"

    s2_figure(OUT / "fig_s2_dose.pdf", slugs, names, lambda s, c, o: count([s], [c], o))

    # Table
    def cell(s, o, cs, fmt="frac"):
        sl = slugs if s == "all" else [s]
        if fmt == "doses":
            return "/".join(str(count(sl, [c], o)[0]) for c in cs)
        k, n = count(sl, cs, o)
        return f"{k}/{n}"
    spec = [
        ("\\textit{Exposure behaviour}", None, None, None),
        ("Listed the wiki before writing (no listing shown)", "listed_before_write", UNSHOWN, "frac"),
        ("Read a seeded page before writing, dose 1/2/4", "read_prior_page", ["dose1", "dose2", "dose4"], "doses"),
        ("\\textit{No seeded convention} (isolated, neutral4, neutral4\\_shown)", None, None, None),
        ("Wrote an index-like page", "index_like", NO_CONVENTION, "frac"),
        ("Page name with a trailing code slot", "adopt_suffix_slot", NO_CONVENTION, "frac"),
        ("\\textit{Arbitrary marker, agent must look itself}", None, None, None),
        ("Exact suffix copied, dose 1/2/4", "adopt_suffix", ["dose1", "dose2", "dose4"], "doses"),
        ("Exact suffix copied, marker only (dose 4)", "adopt_suffix", ["dose4_arbitrary_only"], "frac"),
        ("Body tag copied (all conditions)", "adopt_tag", conds, "frac"),
        ("\\textit{Arbitrary marker, page list shown}", None, None, None),
        ("Code slot in name, dose 1", "adopt_suffix_slot", ["dose1_shown"], "frac"),
        ("\\quad slot filled with own id, dose 1", "suffix_slot_self_id", ["dose1_shown"], "frac"),
        ("Exact suffix copied, dose 1", "adopt_suffix", ["dose1_shown"], "frac"),
        ("Exact suffix copied, dose 4", "adopt_suffix", ["dose4_shown"], "frac"),
        ("\\textit{Functional convention (Answers-Index)}", None, None, None),
        ("Own line in index, dose 1/2/4", "adopt_index", ["dose1", "dose2", "dose4"], "doses"),
        ("Own line in index, index only (dose 4)", "adopt_index", ["dose4_functional_only"], "frac"),
        ("Correct answer (all conditions)", "answer_correct", conds, "frac"),
    ]
    t = ["\\begin{tabular}{@{}l" + "c" * (len(slugs) + 1) + "@{}}", "\\toprule",
         "Outcome & " + " & ".join(names[s] for s in slugs) + " & Pooled \\\\", "\\midrule"]
    for lab, o, cs, fmt in spec:
        if o is None:
            t.append(f"\\multicolumn{{{len(slugs) + 2}}}{{@{{}}l}}{{{lab}}} \\\\")
            continue
        t.append(lab + " & " + " & ".join(cell(s, o, cs, fmt) for s in slugs + ["all"]) + " \\\\")
    t += ["\\bottomrule", "\\end{tabular}"]
    (OUT / "tab_s2.tex").write_text("\n".join(t) + "\n", encoding="utf-8")


def main():
    M = Macros()
    study1(M)
    study2(M)
    M.write(OUT / "numbers.tex")
    print(f"{len(M)} macros written")


if __name__ == "__main__":
    main()
