"""Generate every number and table used in the paper from the two studies' result files.

Study 1 (observational, collusion.wiki): results/macros.json, results/main_results.csv,
    results/technique_catalogue.csv (written by `python -m sord.run_all`).
Study 2 (seeded convention diffusion): experiments/convention_diffusion/results/<model>/trials.jsonl and
    results/summary.json (written by `python -m sord_exp.analyze`).

Writes paper/numbers.tex (\\N{key} macros; a missing key prints a bold ??key) and the table bodies
paper/tab_s1_tech.tex, paper/tab_s1_choice.tex and paper/tab_s2.tex. Models found in the Study 2 results
folder appear in its table automatically.

Usage:  python paper/make_numbers.py
"""
